#!/bin/zsh
set -euo pipefail

# 单文件 ChatGPTBridge 安装器。
# 本文件可移动到任意目录运行，不依赖原项目路径。
#
# 用法：
#
#   /path/to/chat-bridge-install.sh /path/to/git-project
#   /path/to/chat-bridge-install.sh --force /path/to/git-project
#
# --force 用于更新目标项目中已经存在的 Bridge 脚本和说明文档。

script_path="${0:A}"
force=0
target_arg=""

for arg in "$@"; do
    case "$arg" in
        --force)
            force=1
            ;;
        -h|--help)
            print -r -- "用法：$0 [--force] /path/to/git-project"
            exit 0
            ;;
        *)
            if [[ -n "$target_arg" ]]; then
                print -u2 -r -- "错误：只能指定一个目标项目目录。"
                exit 2
            fi
            target_arg="$arg"
            ;;
    esac
done

if [[ -z "$target_arg" ]]; then
    print -u2 -r -- "错误：缺少目标项目目录。"
    print -u2 -r -- "用法：$0 [--force] /path/to/git-project"
    exit 2
fi

if [[ ! -d "$target_arg" ]]; then
    print -u2 -r -- "错误：目标项目目录不存在：$target_arg"
    exit 2
fi

target_dir="$(cd "$target_arg" && pwd)"
if ! target_root="$(git -C "$target_dir" rev-parse --show-toplevel 2>/dev/null)"; then
    print -u2 -r -- "错误：目标目录不是 Git 项目：$target_dir"
    exit 1
fi

target_tools="$target_root/tools"
mkdir -p "$target_tools"

decode_base64() {
    if [[ -x /usr/bin/base64 ]]; then
        if /usr/bin/base64 -D </dev/null >/dev/null 2>&1; then
            /usr/bin/base64 -D
        else
            /usr/bin/base64 -d
        fi
    else
        base64 -d
    fi
}

install_payload() {
    local name="$1"
    local target_file="$2"

    if [[ -e "$target_file" && "$force" -ne 1 ]]; then
        print -u2 -r -- "错误：目标文件已存在：$target_file"
        print -u2 -r -- "如需更新，请追加 --force。"
        exit 1
    fi

    # 源码仓库中优先使用旁边的最新版执行脚本；只有安装器被独立分发时，
    # 才回退到内嵌副本，避免把旧版项目路由逻辑安装到目标项目。
    case "$name" in
        chat-context.sh|chat-apply-shell.sh|chat-apply-hammerspoon.sh|chat-read-last-diff.swift|chat-monitor.sh|chat-monitor.swift|CHAT-BRIDGE.md)
            local adjacent_dir="${script_path:h}"
            [[ "$name" == "CHAT-BRIDGE.md" ]] && adjacent_dir="${script_path:h:h}"
            local adjacent_script="$adjacent_dir/$name"
            if [[ -f "$adjacent_script" && "$adjacent_script" == "$target_file" ]]; then
                return 0
            elif [[ -f "$adjacent_script" ]]; then
                install -m 755 "$adjacent_script" "$target_file"
                return 0
            fi
            ;;
    esac

