# 非 --force 模式先完整检查目标，避免前几个文件已经写入后才在中途失败。
if [[ "$force" -ne 1 ]]; then
    preflight_targets=(
        "$target_tools/chat-apply-shell.sh"
        "$target_tools/chat-apply-hammerspoon.sh"
        "$target_tools/chat-context.sh"
        "$target_tools/chat-read-last-diff.sh"
        "$target_tools/chat-read-last-diff.swift"
        "$target_tools/chat-monitor.sh"
        "$target_tools/chat-monitor.swift"
    )

    if [[ "$script_path" != "$target_tools/chat-bridge-install.sh" ]]; then
        preflight_targets+=("$target_tools/chat-bridge-install.sh")
    fi

    for target_file in "${preflight_targets[@]}"; do
        if [[ -e "$target_file" ]]; then
            print -u2 -r -- "错误：目标文件已存在：$target_file"
